template<size_t N>
array<double, N> scaleSin(const array<double, N>& v, double f) {
  array<double, N> ret;
  ret.at(0) = v.at(0) * f;
  auto f2 = f * f;
  for (u32 i = 1; i < N; ++i) {
    ret.at(i) = v.at(i) * f;
    f *= f2;
  }
  return ret;
}

template<size_t N>
array<double, N> scaleCos(const array<double, N>& v, double f) {
  array<double, N> ret;
  auto f2 = f * f;
  f = 1;
  for (u32 i = 0; i < N; ++i) {
    ret.at(i) = v.at(i) * f;
    f *= f2;
  }
  return ret;
}

